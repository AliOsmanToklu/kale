"""The service's tables. ``jobs`` is also the queue that workers claim from."""

from __future__ import annotations

import enum
import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import JSON, BigInteger, Enum, ForeignKey, Index, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from kale.server.db import Base, UTCDateTime


def _enum(cls: type[enum.StrEnum]) -> Enum:
    return Enum(
        cls,
        native_enum=False,
        length=16,
        values_callable=lambda members: [m.value for m in members],
    )


def _uuid() -> str:
    return str(uuid.uuid4())


class JobKind(enum.StrEnum):
    RUN = "run"
    INVESTIGATE = "investigate"


class JobStatus(enum.StrEnum):
    QUEUED = "queued"
    RUNNING = "running"
    SUCCEEDED = "succeeded"
    FAILED = "failed"
    CANCELLED = "cancelled"

    @property
    def final(self) -> bool:
        return self in (JobStatus.SUCCEEDED, JobStatus.FAILED, JobStatus.CANCELLED)


class Role(enum.StrEnum):
    READER = "reader"
    RUNNER = "runner"

    def allows(self, required: Role) -> bool:
        """Whether a token with this role may do what ``required`` may do."""
        return self is required or self is Role.RUNNER


class Token(Base):
    __tablename__ = "tokens"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    name: Mapped[str] = mapped_column(String(100), unique=True, index=True)
    role: Mapped[Role] = mapped_column(_enum(Role))
    # SHA-256 of the raw token; the raw token is shown once and never stored.
    digest: Mapped[str] = mapped_column(String(64), unique=True, index=True)
    # The first characters after "kale_", so a token can be recognized in a list.
    prefix: Mapped[str] = mapped_column(String(8))
    created_at: Mapped[datetime] = mapped_column(UTCDateTime)
    last_used_at: Mapped[datetime | None] = mapped_column(UTCDateTime, default=None)
    revoked_at: Mapped[datetime | None] = mapped_column(UTCDateTime, default=None)


class Upload(Base):
    __tablename__ = "uploads"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_uuid)
    # Generated by the server; never derived from the client's file name.
    stored_path: Mapped[str] = mapped_column(String(1024))
    # For display only: base name, control characters removed, at most 255 characters.
    original_name: Mapped[str] = mapped_column(String(255))
    size: Mapped[int] = mapped_column(BigInteger)
    sha256: Mapped[str] = mapped_column(String(64))
    created_at: Mapped[datetime] = mapped_column(UTCDateTime)
    deleted_at: Mapped[datetime | None] = mapped_column(UTCDateTime, default=None)


class Job(Base):
    __tablename__ = "jobs"
    __table_args__ = (Index("ix_jobs_status_created_at", "status", "created_at"),)

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=_uuid)
    kind: Mapped[JobKind] = mapped_column(_enum(JobKind))
    module: Mapped[str | None] = mapped_column(String(100), default=None)
    # An Observable as JSON; for an upload the value is the quarantine path.
    target: Mapped[dict[str, Any]] = mapped_column(JSON)
    options: Mapped[dict[str, Any]] = mapped_column(JSON)
    # {"entries": [...], "allow_private": bool}: the scope after narrowing.
    scope: Mapped[dict[str, Any]] = mapped_column(JSON)
    lang: Mapped[str] = mapped_column(String(8))
    status: Mapped[JobStatus] = mapped_column(_enum(JobStatus), default=JobStatus.QUEUED)
    created_by: Mapped[int] = mapped_column(ForeignKey("tokens.id"))
    created_at: Mapped[datetime] = mapped_column(UTCDateTime)
    started_at: Mapped[datetime | None] = mapped_column(UTCDateTime, default=None)
    finished_at: Mapped[datetime | None] = mapped_column(UTCDateTime, default=None)
    heartbeat_at: Mapped[datetime | None] = mapped_column(UTCDateTime, default=None)
    worker_id: Mapped[str | None] = mapped_column(String(255), default=None)
    attempts: Mapped[int] = mapped_column(Integer, default=0)
    # A ModuleResult or an Investigation, once the job succeeded.
    result: Mapped[dict[str, Any] | None] = mapped_column(JSON, default=None)
    # Infrastructure failures only; a module's own error is part of the result.
    error: Mapped[str | None] = mapped_column(Text, default=None)
    upload_id: Mapped[str | None] = mapped_column(ForeignKey("uploads.id"), default=None)

    upload: Mapped[Upload | None] = relationship(lazy="joined")
    token: Mapped[Token] = relationship(lazy="joined")
